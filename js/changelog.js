const Changelog = (() => {
  const h = (...a) => UI.h(...a);
  // во ВКонтакте пункты про Telegram не показываем
  const items = (c) => (typeof Platform !== 'undefined' && Platform.kind() === 'vk' ? c.items.filter((t) => !/Telegram/.test(t)) : c.items);
  const cur = () => CHANGES.find((c) => c.v === CONFIG.version) || null;

  function block(c, main) {
    return h('div', { class: 'cl-block' + (main ? ' main' : '') },
      h('div', { class: 'cl-head' }, h('b', null, 'Версия ' + c.v), h('small', null, c.date)),
      h('ul', { class: 'cl-list' }, items(c).map((t) => h('li', null, t))));
  }

  function open() {
    const now = cur();
    const rest = CHANGES.filter((c) => c !== now);
    UI.modal({
      title: 'Что нового', sheet: true, cls: 'fixed-h changelog-modal',
      body: h('div', { class: 'cv-wrap' }, h('div', { class: 'cv-box' },
        now ? block(now, true) : h('p', { class: 'note center' }, 'Версия ' + CONFIG.version),
        rest.length ? h('div', { class: 'cl-sep' }, 'Раньше') : null,
        rest.map((c) => block(c, false)))),
      actions: [{ label: 'Отлично!' }]
    });
  }

  // при запуске: новая версия - показываем один раз (новичкам не показываем)
  function check() {
    const s = Econ.s;
    const v = CONFIG.version;
    if (s.seenVer === v) return;
    const veteran = !!s.seenVer || s.le > 0 || s.taps > 0;
    s.seenVer = v;
    if (window.Game) Game.save();
    if (!veteran || !cur()) return;
    const tryOpen = (n) => {
      if (UI.isModalOpen() || UI.screen() !== 'main') { if (n < 40) setTimeout(() => tryOpen(n + 1), 1500); return; }
      open();
    };
    setTimeout(() => tryOpen(0), 2500);
  }

  return { open, check, list: CHANGES };
})();
